"""Cut the replay fixture for tests/test_replay.c out of the phase-probe recording.

    python3 -I tools/make-fixture.py <phase-probe.bin> <marks.txt> > tests/fixtures/replay.h

The recording is 80-byte records (phase-probe/phase-probe.c, struct rec). The fixture keeps the
tick records (src == 1) of the first 10 s after the E1, E2 and E4 start marks, one array each:
E1 two decks at different tempos, E2 near-equal tempo apart, E4 deck 1 synced to deck 2.
"""
import struct
import sys

REC = struct.Struct("<QIBBBB" "2d2d2d2d")  # t0_ns dt_ns src grid play load pos[2] ph[2] bpm[2] bar[2]
assert REC.size == 80

SEGMENTS = (  # (array name, mark name)
    ("REPLAY_DIFF_TEMPO", "E1_start_diff_tempo"),
    ("REPLAY_APART", "E2_start_equal_tempo_nosync"),
    ("REPLAY_SYNC", "E4_start_deck1_sync"),
)
SPAN_S = 10.0
SRC_TICK = 1
BOTH = 3  # bits 0 and 1: deck 1 and deck 2


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: make-fixture.py <phase-probe.bin> <marks.txt>")
    data = open(argv[1], "rb").read()
    marks = {}
    for line in open(argv[2]):
        parts = line.split()
        if len(parts) == 3 and parts[0] == "MARK":
            marks[parts[1]] = float(parts[2])
    recs = [REC.unpack_from(data, o) for o in range(0, len(data) - REC.size + 1, REC.size)]

    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Generated by tools/make-fixture.py from phase-probe/.scratch/phase-probe.bin and marks.txt. Do not edit. */",
           "#ifndef PL_REPLAY_H", "#define PL_REPLAY_H", "", "#include <stdint.h>", "",
           "struct replay_tick { uint32_t t_ms; double ph1, ph2, bpm1, bpm2; };", ""]
    for name, mark in SEGMENTS:
        a = marks[mark]
        rows = [r for r in recs if r[2] == SRC_TICK and a <= r[0] / 1e9 < a + SPAN_S]
        if not rows:
            sys.exit("no tick records after mark " + mark)
        for r in rows:  # the test turns everything else on: say so only if the recording agrees
            if r[3] & BOTH != BOTH or r[4] & BOTH != BOTH or r[5] & BOTH != BOTH:
                sys.exit("%s: a tick without grid, playing or loaded on both decks" % mark)
        out.append("/* %s: %d ticks from mark %s (%.2f s) */" % (name, len(rows), mark, a))
        out.append("#define %s_N %d" % (name, len(rows)))
        out.append("static const struct replay_tick %s[%s_N] = {" % (name, name))
        for r in rows:
            t_ms = (r[0] // 1000000) & 0xFFFFFFFF
            ph, bpm = r[8:10], r[10:12]
            out.append("    { %du, %.17g, %.17g, %.17g, %.17g }," % (t_ms, ph[0], ph[1], bpm[0], bpm[1]))
        out.append("};")
        out.append("")
    out.append("#endif")
    print("\n".join(out))


main(sys.argv)
