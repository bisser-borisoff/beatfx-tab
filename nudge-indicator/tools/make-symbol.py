"""Draw the tempo symbol (two overlapping circles) and write it as symbol.h.

    python3 tools/make-symbol.py > symbol.h

Two bitmaps of SYM_W x SYM_H pixels, RGBA, already laid over the box's black background
(alpha 255, so premultiplied and straight alpha are the same bytes):
  SYM_DIFF   the tempos differ: two outlines in the grey of "ms" (quiet: this is the usual state)
  SYM_MATCH  the tempos match: two filled circles in the lock green, a dark arc where they overlap
Needs Pillow. The sizes and colours below repeat geometry.h; change both together.
"""
from PIL import Image, ImageDraw

W, H = 26, 16            # SYM_W, SYM_H
D, STEP, STROKE = 16, 10, 2
GREY = (0x96, 0x96, 0x96)    # COL_UNIT
GREEN = (0x2E, 0xE0, 0x6A)   # COL_LOCK
DARK = (0x00, 0x3C, 0x18)    # the arc between the two filled circles
SS = 8                   # drawn 8 times larger, then scaled down


def draw(match):
    big = Image.new("RGB", (W * SS, H * SS), (0, 0, 0))
    d = ImageDraw.Draw(big)
    a = (0, 0, D * SS - 1, D * SS - 1)
    b = (STEP * SS, 0, (STEP + D) * SS - 1, D * SS - 1)
    w = STROKE * SS
    if match:
        d.ellipse(a, fill=GREEN)
        d.ellipse(b, fill=GREEN)
        d.arc(a, -62, 62, fill=DARK, width=w)
        d.arc(b, 118, 242, fill=DARK, width=w)
    else:
        d.ellipse(a, outline=GREY, width=w)
        d.ellipse(b, outline=GREY, width=w)
    return big.resize((W, H), Image.BOX)  # a plain average: no overshoot past the colours above


def array(name, im):
    out = ["static const unsigned char %s[SYM_W * SYM_H * 4] = {" % name]
    px = list(im.getdata())
    for y in range(H):
        row = px[y * W:(y + 1) * W]
        out.append("    " + " ".join("%d,%d,%d,255," % p for p in row))
    out.append("};")
    return out


def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Generated by tools/make-symbol.py. Do not edit. */",
           "#ifndef PL_SYMBOL_H", "#define PL_SYMBOL_H", "", '#include "geometry.h"', ""]
    out += array("SYM_DIFF", draw(False)) + [""] + array("SYM_MATCH", draw(True))
    out += ["", "#endif"]
    print("\n".join(out))


main()
